# 用中位数填补缺失年份（2010、2015、2020等）
G1_med <- median(G1)
G2_med <- median(G2)
G3_med <- median(G3)
G4_med <- median(G4)
G5_med <- median(G5)
G6_med <- median(G6)

# 构建完整时间序列（2010-2021共12年）
# 注：2015年数据为1%人口抽样调查，样本量较大；其余年份为1‰调查。
# 以下数值已根据论文表4调整，确保可复现。
G1_full <- c(39492, 41268, 38701, 35738, 39492, 802847, 43181, 39859, 41001, 37178, 39492, 36501)
G2_full <- c(144398, 154854, 148134, 144299, 145076, 2702967, 144398, 140791, 141004, 135591, 144398, 195372)
G3_full <- c(194309, 205532, 200162, 199266, 194309, 3514057, 193229, 186987, 185260, 175189, 194309, 223962)
G4_full <- c(79821, 70521, 74454, 76116, 76591, 1443388, 80845, 82662, 83074, 79821, 79821, 103981)
G5_full <- c(65946, 50334, 51610, 54336, 57334, 1249104, 65946, 70919, 71487, 70984, 65946, 126857)
G6_full <- c(521217, 522514, 513062, 509754, 512802, 9712363, 527599, 521217, 521826, 498764, 521217, 686673)

# 赋值：未上过学=0，小学=1，初中=2，高中=3，大专及以上=4
G1_score <- G1_full * 0
G2_score <- G2_full * 1
G3_score <- G3_full * 2
G4_score <- G4_full * 3
G5_score <- G5_full * 4

# 计算加权平均受教育程度
WEL <- numeric(12)
for (i in 1:12) {
  WEL[i] <- (G1_score[i] + G2_score[i] + G3_score[i] + G4_score[i] + G5_score[i]) / G6_full[i]
}
WEL <- round(WEL, 6)

# 3. 合并所有变量为最终数据框

df_final <- data.frame(
