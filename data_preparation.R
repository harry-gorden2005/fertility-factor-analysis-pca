# ---------- 以下为计算衍生指标所需的原始数据 ----------

# 年末总人口（万人），2009-2021年（共13年，用于计算结婚率时的期初/期末平均）
vec1 <- c(133450, 134091, 134916, 135922, 136726, 137646, 138326, 139232, 140011, 140541,
          141008, 141212, 141260)
# 结婚登记对数（万对），2010-2021年
vec2 <- c(1212.40, 1241.00, 1302.36, 1323.59, 1346.93, 1306.74, 1224.71, 1142.82, 1063.10,
          1013.94, 927.33, 814.33)
# 内地居民初婚登记人数（万人），2010-2021年
vec3 <- c(2200.90, 2309.88, 2361.17, 2385.96, 2286.81, 2108.97, 1913.26, 1746.33, 1598.67,
          1398.71, 1228.60, 1157.80)
# 15-64岁人口（万人），2010-2021年
vec4 <- c(99938, 100378, 100718, 101041, 101032, 100978, 100943, 100528, 100065, 99552, 96871, 96526)
# 城镇人口（万人），2010-2021年
