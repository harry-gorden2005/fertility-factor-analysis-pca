# 年末总人口（万人），2010-2021年（用于城镇化率分母）
vec6 <- c(134091, 134916, 135922, 136726, 137646, 138326, 139232, 140011, 140541,
          141008, 141212, 141260)

# 2. 计算衍生指标

# 2.1 结婚率（‰）—— 公式：结婚登记对数*10000 / 年平均人口 * 1000
#     年平均人口 = (当年期初人口 + 当年期末人口)/2
#     期初人口 = vec1[i], 期末人口 = vec1[i+1]（对应2009-2021）
#     注意：vec2长度为12，vec1长度为13，使用i从1到12
marriage_rate <- numeric(12)
for (i in 1:12) {
  avg_pop <- (vec1[i] + vec1[i+1]) / 2          # 年平均人口（万人）
  marriage_rate[i] <- (vec2[i] * 10000) / avg_pop * 1000
}
# 保留两位小数
marriage_rate <- round(marriage_rate, 2)

# 2.2 初婚率（‰）—— 公式：初婚登记人数 / 15-64岁人口 * 1000
first_marriage_rate <- (vec3 / vec4) * 1000
first_marriage_rate <- round(first_marriage_rate, 2)

# 2.3 城镇化率 —— 公式：城镇人口 / 年末总人口
urbanization_rate <- vec5 / vec6
urbanization_rate <- round(urbanization_rate, 2)

# 2.4 女性受教育程度均值（基于抽样数据，使用中位数填补缺失）
#     原始抽样数据（部分年份，需要填补缺失）
G1 <- c(41268, 38701, 35738, 39492, 43181, 39859, 41001, 37178, 36501)   # 未上过学
